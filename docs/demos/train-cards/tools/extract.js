/* Extract each rolling-stock illustration from the artwork sheets into a standalone,
 * namespaced SVG fragment so many of them can live in one HTML document without
 * their `.cls-N` rules / clipPath ids colliding. */
const fs = require('fs');
const path = require('path');

const ROOT = process.argv[2];
const OUT = process.argv[3];
fs.mkdirSync(OUT, { recursive: true });

function parse(file) {
  const src = fs.readFileSync(file, 'utf8');
  const style = src.match(/<style>([\s\S]*?)<\/style>/)[1];
  const defs = src.match(/<defs>([\s\S]*?)<\/defs>/)[1];
  return { src, style, defs };
}

/** css rules → [{selectors:[...], body}] preserving order */
function rules(style) {
  const out = [];
  for (const m of style.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    out.push({ sel: m[1].split(',').map((s) => s.trim()).filter(Boolean), body: m[2].trim() });
  }
  return out;
}

/** clipPath / gradient blocks in <defs>, keyed by id */
function defBlocks(defs) {
  const out = {};
  for (const m of defs.matchAll(/<(clipPath|linearGradient|radialGradient)\b[^>]*id="([^"]+)"[\s\S]*?<\/\1>/g)) {
    out[m[2]] = m[0];
  }
  return out;
}

/** Namespace every cls-N and every def id inside a chunk of markup. */
function namespaceAll(markup, prefix, ids) {
  let s = markup.replace(/\bcls-(\d+)\b/g, `${prefix}c$1`);
  for (const id of ids) {
    // ids can contain regex-special chars (they're autogenerated Illustrator names)
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    s = s.replace(new RegExp(`id="${esc}"`, 'g'), `id="${prefix}${sanitize(id)}"`);
    s = s.replace(new RegExp(`url\\(#${esc}\\)`, 'g'), `url(#${prefix}${sanitize(id)})`);
    s = s.replace(new RegExp(`xlink:href="#${esc}"`, 'g'), `xlink:href="#${prefix}${sanitize(id)}"`);
  }
  return s;
}
const sanitize = (id) => id.replace(/[^A-Za-z0-9_-]/g, '');

/**
 * NIGHT LIVERY — the dark-mode repaint, authored hex → dark hex.
 *
 * The sheet is drawn on a near-black page, so its bodywork is near-white. Dropped onto a dark
 * card face (~#24272a) an unmodified body is a glare bomb: ~12:1 against the face, brighter than
 * anything else in a dark UI. Dark mode walks the whole neutral ramp down into a slate range,
 * keeping the ORDER of the greys intact — a roof that was darker than its body stays darker — so
 * every car keeps its modelling and just stops shouting.
 *
 * Two things are deliberately left alone:
 *   · Liveries. The red/orange/yellow/green/blue/purple bands and R20's rainbow ARE the card's
 *     identity, and they read better than ever once the body around them is no longer white.
 *   · Windows and door bands. They were the darkest inks and they stay the darkest, which still
 *     clears ~2:1 against the toned-down body — no need to invert them into lit glazing.
 */
const parseHex = (hex) => {
  const h = hex.replace('#', '').toLowerCase();
  const n = parseInt(h.length === 3 ? [...h].map((c) => c + c).join('') : h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const toHex = (rgb) =>
  '#' + rgb.map((v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, '0')).join('');
const mix = (a, b, t) => {
  const [A, B] = [parseHex(a), parseHex(b)];
  return toHex(A.map((c, i) => c + (B[i] - c) * t));
};

/**
 * The ramp is DIMMED, not repainted — every authored neutral is mixed toward the ground by one
 * constant. Hand-picking dark values is what makes a night livery look wrong: the authored greys
 * are neutral (#fff, #efeeef, #dbdcdc, #c8c9ca …) and any hue introduced here reads as a car that
 * has been recoloured rather than a car seen in low light. Mixing keeps each ink's own hue and
 * the spacing between them, so the cars still look like themselves.
 */
const NIGHT_GROUND = '#1a1d20'; // the app's dark paper — a hair cooler than black, never blue
const DIM = 0.415; // enough to kill the glare, not so much that a pale car stops reading as pale
const BODY_NEUTRALS = [
  '#ffffff', // bodywork
  '#efeeef',
  '#dbdcdc',
  '#c8c9ca', // roofs, skirts
  '#b5b4b5',
  '#b4b4b5',
  '#9e9e9f',
  '#888888', // bogies, wheel strokes
  '#717071',
  '#717072',
];
const NIGHT_BODY = Object.fromEntries(BODY_NEUTRALS.map((h) => [h, mix(h, NIGHT_GROUND, DIM)]));

/** Per-car departures from the night livery. */
const PER_CAR = {
  // The open wagon inverts the usual problem: its body IS the dark navy family, so on a dark
  // face it read as a hole rather than a vehicle. Lift that family into a lit steel range
  // instead of darkening it, and hold its frame above the body — the frame is the only
  // structure an open wagon has.
  // The open wagon is the one car dimming cannot help: its body already IS the dark navy family,
  // and on the black card's face (~#24272a) it read as a hole rather than a vehicle. Lift that
  // family into a lit steel range instead. Its frame stays on the shared ramp, which still lands
  // well above the lifted body — an open wagon is read entirely by its frame.
  BLACK: {
    '#12222f': '#465c70', // outer frame / skirt
    '#142536': '#4d647a', // sill + rib strokes
    '#242e3a': '#54697d', // interior back wall
    '#334454': '#647d94', // interior panels
    '#64717a': '#93a3ae', // interior highlight
  },
};

const expand = (hex) => {
  const h = hex.replace('#', '').toLowerCase();
  return '#' + (h.length === 3 ? h.split('').map((c) => c + c).join('') : h);
};
const darkInkFor = (key) => {
  const merged = { ...NIGHT_BODY, ...(PER_CAR[key] ?? {}) };
  return Object.fromEntries(Object.entries(merged).map(([k, v]) => [expand(k), v]));
};

/** `.sel { fill: #aaa }` → the dark-mode counterpart, or null when nothing in it is remapped. */
function darkRule(sel, body, remap) {
  const decls = [];
  for (const m of body.matchAll(/(fill|stroke)\s*:\s*(#[0-9a-fA-F]{3}|#[0-9a-fA-F]{6})\b/g)) {
    const to = remap[expand(m[2])];
    if (to) decls.push(`${m[1]}: ${to}`);
  }
  return decls.length ? `${sel} { ${decls.join('; ')} }` : null;
}

/** Build one standalone <svg> for a body of markup, carrying only the rules/defs it uses. */
function build({ style, defs, body, prefix, viewBox, darkInk }) {
  const usedCls = new Set([...body.matchAll(/\bcls-(\d+)\b/g)].map((m) => m[1]));
  // a class referenced by a kept rule (e.g. `.cls-7 { clip-path: url(#x) }`) can pull in defs
  const allDefs = defBlocks(defs);
  const keptRules = [];
  let grew = true;
  const kept = new Set(usedCls);
  while (grew) {
    grew = false;
    for (const r of rules(style)) {
      const hit = r.sel.some((s) => [...kept].some((n) => s === `.cls-${n}`));
      if (!hit) continue;
      for (const m of r.body.matchAll(/\bcls-(\d+)\b/g)) if (!kept.has(m[1])) { kept.add(m[1]); grew = true; }
    }
  }
  for (const r of rules(style)) {
    const sel = r.sel.filter((s) => [...kept].some((n) => s === `.cls-${n}`));
    if (sel.length) keptRules.push(`${sel.join(', ')} { ${r.body} }`);
  }
  // defs referenced by the body or by a kept rule
  const refText = body + keptRules.join('\n');
  const usedIds = new Set();
  let scan = true;
  let pool = refText;
  while (scan) {
    scan = false;
    for (const m of pool.matchAll(/url\(#([^)]+)\)/g)) {
      if (allDefs[m[1]] && !usedIds.has(m[1])) { usedIds.add(m[1]); pool += allDefs[m[1]]; scan = true; }
    }
  }
  const ids = [...usedIds];
  const defsMarkup = ids.map((id) => allDefs[id]).join('\n    ');

  // Dark mode: the OS preference is the default signal; an explicit data-theme on the host
  // document wins in BOTH directions (higher specificity than the media query's bare .cls
  // selectors). Standalone — as a file or an <img> — only the media query can apply, which is
  // the right fallback.
  let dark = '';
  if (darkInk) {
    const remap = darkInk;
    const media = [], onDark = [], onLight = [];
    for (const r of rules(style)) {
      const sel = r.sel.filter((s) => [...kept].some((n) => s === `.cls-${n}`));
      if (!sel.length) continue;
      const flipped = darkRule(sel.join(', '), r.body, remap);
      if (!flipped) continue;
      media.push('  ' + flipped);
      onDark.push(darkRule(sel.map((s) => `:root[data-theme='dark'] ${s}`).join(', '), r.body, remap));
      onLight.push(`${sel.map((s) => `:root[data-theme='light'] ${s}`).join(', ')} { ${r.body} }`);
    }
    if (media.length) {
      dark =
        `\n\n      /* Dark mode — night livery, see NIGHT_BODY / PER_CAR in tools/extract.js. */\n` +
        `      @media (prefers-color-scheme: dark) {\n      ${media.join('\n      ')}\n      }\n` +
        `      ${onDark.join('\n      ')}\n      ${onLight.join('\n      ')}`;
    }
  }
  const css = keptRules.join('\n      ') + dark;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="${viewBox}" class="rs-art" aria-hidden="true" focusable="false">\n` +
    `  <defs>\n    <style>\n      ${css}\n    </style>\n    ${defsMarkup}\n  </defs>\n` +
    `  ${body.trim()}\n</svg>\n`;
  return namespaceAll(svg, prefix, ids);
}

